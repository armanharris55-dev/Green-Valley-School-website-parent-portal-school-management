-- Green Valley School — MySQL / MariaDB schema (utf8mb4)
CREATE TABLE IF NOT EXISTS users (
  id VARCHAR(20) NOT NULL PRIMARY KEY,
  login VARCHAR(80) NOT NULL UNIQUE,
  pass_hash VARCHAR(255) NOT NULL,
  role VARCHAR(12) NOT NULL,
  ref VARCHAR(24) NOT NULL DEFAULT '',
  name VARCHAR(120) NOT NULL DEFAULT '',
  active TINYINT(1) NOT NULL DEFAULT 1,
  demo TINYINT(1) NOT NULL DEFAULT 0,
  t BIGINT NOT NULL DEFAULT 0,
  KEY role_idx (role), KEY ref_idx (ref)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rec (
  id VARCHAR(24) NOT NULL PRIMARY KEY,
  k VARCHAR(12) NOT NULL,
  cls VARCHAR(8) NOT NULL DEFAULT '',
  sid VARCHAR(24) NOT NULL DEFAULT '',
  d MEDIUMTEXT NOT NULL,
  t BIGINT NOT NULL DEFAULT 0,
  KEY k_cls (k, cls), KEY k_sid (k, sid), KEY k_t (k, t)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS att (
  day DATE NOT NULL,
  sid VARCHAR(24) NOT NULL,
  cls VARCHAR(8) NOT NULL,
  st CHAR(1) NOT NULL,
  PRIMARY KEY (day, sid),
  KEY cls_day (cls, day), KEY sid_day (sid, day)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS site (
  name VARCHAR(40) NOT NULL PRIMARY KEY,
  d MEDIUMTEXT NOT NULL,
  t BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS attempts (
  k VARCHAR(80) NOT NULL,
  t INT NOT NULL,
  KEY k_t (k, t)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
